"""Lessons: errors the models made in Blender, with the solution that worked.

Every model keeps its own lessons: a status page blender-assistant.md and one
page per lesson in lessons/<model>/, in the folder set in Preferences › Learning
(e.g. inside an Obsidian vault), otherwise in the add-on's folder. The short
rules of a model's newest lessons go into its system prompt. This module does
not import ``bpy``.
"""

import datetime
import json
import os
import re

PROJECT = "blender-assistant"
AREA_DIR = "30 Private"
INDEX_FILE = PROJECT + ".md"
INDEX_START = "<!-- lessons:start (generated by the Blender add-on) -->"
INDEX_END = "<!-- lessons:end -->"


def _today():
    return datetime.date.today().isoformat()


def slug(text, limit=60):
    text = text.lower().replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss")
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")[:limit].strip("-") or "lesson"


def find_vault():
    """Path of an Obsidian vault named CLAUDE with a "30 Private" area (where lessons were kept before
    the folder could be set), or None. Only used once to keep that place (settings.py)."""
    config = os.path.expanduser("~/Library/Application Support/obsidian/obsidian.json")
    try:
        with open(config, encoding="utf-8") as f:
            vaults = (json.load(f).get("vaults") or {}).values()
    except (OSError, ValueError):
        return None
    for vault in vaults:
        path = vault.get("path") or ""
        if os.path.basename(path.rstrip("/")) == "CLAUDE" and os.path.isdir(os.path.join(path, AREA_DIR)):
            return path
    return None


def project_dir(configured, workdir):
    """Folder of the lessons project (…/blender-assistant)."""
    if configured:
        return os.path.expanduser(configured)
    return os.path.join(workdir, "lessons")


def _ensure_project(root):
    os.makedirs(os.path.join(root, "lessons"), exist_ok=True)
    index = os.path.join(root, INDEX_FILE)
    if not os.path.exists(index):
        with open(index, "w", encoding="utf-8") as f:
            f.write("---\ntype: project\narea: private\nproject: blender-assistant\nstatus: active\n"
                    f"updated: {_today()}\n---\n\n"
                    "# Blender Assistant\n\n"
                    "Errors the AI models of the Blender add-on \"Claude Assistant\" made, with the solution "
                    "that worked. Written automatically by the add-on: one page per lesson in "
                    "`lessons/<model>/` (page type `lesson`). Each model only gets its own lessons in its "
                    "prompt. Edit or delete pages freely; the add-on regenerates the list below.\n\n"
                    f"{INDEX_START}\n{INDEX_END}\n")
    return root


# ---------------------------------------------------------------------------
# Pages

def _frontmatter(text):
    meta = {}
    if text.startswith("---"):
        end = text.find("\n---", 3)
        for line in text[3:end].splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip().strip('"')
    return meta


def _quote(value):
    return json.dumps(" ".join(str(value).split()), ensure_ascii=False)


def _page(title, model_name, model_slug, rule, error, solution, created, updated, history=""):
    return (
        "---\n"
        f"title: {_quote(title)}\n"
        "type: lesson\n"
        "area: private\n"
        f"project: {PROJECT}\n"
        f"tags: [blender, bpy, lesson, {model_slug}]\n"
        f"model: {_quote(model_name)}\n"
        f"rule: {_quote(rule)}\n"
        f"created: {created}\n"
        f"updated: {updated}\n"
        "sources: []\n"
        "---\n\n"
        f"# {title}\n\n"
        f"**Rule:** {rule}\n\n"
        f"## Error\n\n```\n{error.strip()}\n```\n\n"
        f"## Solution\n\n{solution.strip()}\n"
        + (f"\n## History\n\n{history.strip()}\n" if history.strip() else "")
    )


def save(root, model_slug, model_name, title, rule, error, solution):
    """Write or update a lesson page. Returns (page name, created?)."""
    _ensure_project(root)
    folder = os.path.join(root, "lessons", model_slug)
    os.makedirs(folder, exist_ok=True)
    name = slug(title)
    path = os.path.join(folder, name + ".md")
    today = _today()
    created, history, is_new = today, "", True
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
        meta = _frontmatter(old)
        created = meta.get("created", today)
        prev = old.split("\n## History\n", 1)
        history = prev[1] if len(prev) > 1 else ""
        history += (f"\n- Revised {today}: the error happened again; solution updated. "
                    f"Previous rule: {meta.get('rule', '')}")
        is_new = False
    with open(path, "w", encoding="utf-8") as f:
        f.write(_page(title, model_name, model_slug, rule, error, solution, created, today, history))
    _rebuild_index(root)
    return name, is_new


def _lessons(root, model_slug=None):
    out = []
    base = os.path.join(root, "lessons")
    if not os.path.isdir(base):
        return out
    for model in sorted(os.listdir(base)):
        folder = os.path.join(base, model)
        if not os.path.isdir(folder) or (model_slug and model != model_slug):
            continue
        for file in os.listdir(folder):
            if not file.endswith(".md"):
                continue
            try:
                with open(os.path.join(folder, file), encoding="utf-8") as f:
                    meta = _frontmatter(f.read(2000))
            except OSError:
                continue
            out.append(dict(meta, page=file[:-3], model_slug=model))
    out.sort(key=lambda m: m.get("updated", ""), reverse=True)
    return out


def _rebuild_index(root):
    by_model = {}
    for lesson in _lessons(root):
        by_model.setdefault(lesson.get("model") or lesson["model_slug"], []).append(lesson)
    lines = [INDEX_START]
    for model in sorted(by_model):
        lines.append(f"\n## Lessons — {model}")
        for lesson in by_model[model]:
            lines.append(f"- [[{lesson['page']}]] — {lesson.get('rule', '')} ({lesson.get('updated', '')})")
    lines.append(INDEX_END)
    index = os.path.join(root, INDEX_FILE)
    with open(index, encoding="utf-8") as f:
        text = f.read()
    if INDEX_START in text and INDEX_END in text:
        text = text[:text.index(INDEX_START)] + "\n".join(lines) + text[text.index(INDEX_END) + len(INDEX_END):]
    else:
        text = text.rstrip("\n") + "\n\n" + "\n".join(lines) + "\n"
    with open(index, "w", encoding="utf-8") as f:
        f.write(text)


def prompt_section(root, model_slug, max_chars=1500):
    """The model's own newest lesson rules for the system prompt (within a character budget)."""
    lines, used = [], 0
    for lesson in _lessons(root, model_slug):
        line = f"- {lesson.get('title', '')}: {lesson.get('rule', '')}"
        if used + len(line) > max_chars:
            break
        lines.append(line)
        used += len(line)
    if not lines:
        return ""
    return ("\nLessons from your earlier errors in Blender (avoid repeating them):\n" + "\n".join(lines) + "\n")


def count(root, model_slug):
    return len(_lessons(root, model_slug))
